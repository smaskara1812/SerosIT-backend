"""Builds core/lookup_consumers.py: which pages may read which master (or shared list) as a dropdown source.

    cd backend
    .venv/bin/python scripts/build_lookup_consumers.py          # rewrite the file
    .venv/bin/python scripts/build_lookup_consumers.py --check  # exit 1 if the file is out of date

A person may read a master's list as a dropdown source only if they hold View, Add or Edit on a page that picks
from it (and only its lookup columns come back). This script reads the frontend to find those pages, so nobody has
to remember to register a new dropdown: it looks at every page file under frontend/src/routes (the pages that
name a menu key) and at the schemas in config/mastersSchemas.js, finds every API call each one makes, and records,
for each list that can serve lookups, the menu keys of the pages that call it.

Run it after adding or changing a page or a dropdown, and commit the file it writes. The self-test fails if the
file is out of date (scripts/check_lookup_access.py).
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings")

import django

django.setup()

from django.urls import resolve

from core.models import SysMenu

FRONTEND = os.path.join(os.path.dirname(ROOT), "frontend", "src")
OUT = os.path.join(ROOT, "core", "lookup_consumers.py")
URL_RE = re.compile(r"""['"`](/api/[A-Za-z0-9_\-/]+/(?:\?[^'"`\s]*)?)['"`]""")
REMOTE_RE = re.compile(r"remote:\s*[`'\"]([^`'\"]+)[`'\"]")
DECLARED_RE = re.compile(r"(?:MENU_KEY|ENTITY_KEY|menuKey|MENU)\s*[:=]\s*['\"]([a-z_.0-9]+)['\"]")


def urls_in(text, keep_query=False):
    found = set(URL_RE.findall(text))
    found.update(u for u in REMOTE_RE.findall(text) if u.startswith("/api/"))
    cleaned = {re.sub(r"\$\{[^&]*", "1", u) for u in found}  # a placeholder (and anything cut off after it) becomes 1
    return cleaned if keep_query else {u.split("?")[0] for u in cleaned}


def entity_of(url):
    """The list's key if its view can serve lookups, else None."""
    try:
        cls = resolve(url).func.cls
    except Exception:
        return None
    if getattr(cls, "lookup", True) is False:
        return None
    key = getattr(cls, "lookup_entity", None) or getattr(cls, "entity_key", None)
    capable = getattr(cls, "is_lookup_capable", None)
    return key if (key and capable and capable()) else None


def references():
    """Every (where, menu keys, url with its query string) the frontend uses: each page file that names a menu key, and
    each master schema in config/mastersSchemas.js (which belongs to that schema's menu key)."""
    valid = {m.menu_key for m in SysMenu.objects.all()}
    refs = []
    routes = os.path.join(FRONTEND, "routes")
    for folder, _, files in os.walk(routes):
        for name in files:
            if not name.endswith(".jsx") or name == "MasterCrudPage.jsx":
                continue
            with open(os.path.join(folder, name), encoding="utf-8") as fh:
                text = fh.read()
            declared = {k for k in DECLARED_RE.findall(text) if k in valid}
            keys = declared or {k for k in re.findall(r"['\"]([a-z_]+\.[a-z_0-9]+)['\"]", text) if k in valid}
            if not keys:
                continue
            where = os.path.relpath(os.path.join(folder, name), routes)
            refs.extend((where, keys, url) for url in sorted(urls_in(text, keep_query=True)))
    with open(os.path.join(FRONTEND, "config", "mastersSchemas.js"), encoding="utf-8") as fh:
        lines = fh.read().split("\n")
    starts = [(i, m.group(1)) for i, l in enumerate(lines) if (m := re.match(r"^  ['\"]?([a-z0-9\-_]+)['\"]?:\s*\{\s*$", l))]
    for n, (start, slug) in enumerate(starts):
        end = starts[n + 1][0] if n + 1 < len(starts) else len(lines)
        block = "\n".join(lines[start:end])
        m = re.search(r"menuKey:\s*['\"]([^'\"]+)['\"]", block)
        if not m or m.group(1) not in valid:
            continue
        refs.extend((f"mastersSchemas.js:{slug}", {m.group(1)}, url) for url in sorted(urls_in(block, keep_query=True)))
    return refs


def build():
    consumers = {}
    for _where, keys, url in references():
        entity = entity_of(url.split("?")[0])
        if not entity:
            continue
        for k in keys:
            if k != entity:  # a page reading its own list needs no lookup rule
                consumers.setdefault(entity, set()).add(k)
    return {k: tuple(sorted(v)) for k, v in sorted(consumers.items())}


def render(consumers):
    lines = [
        '"""GENERATED by scripts/build_lookup_consumers.py. Do not edit by hand; rerun the script.',
        "",
        "Which pages (menu keys) may read each list as a dropdown source. A person who holds View, Add or Edit on one of",
        "these pages may read that list's lookup columns even without rights on the list's own page. Everyone else is",
        'refused. See core/permissions.py (HasMenuPermissionOrLookup) and the "Dropdowns" section of docs/login-and-access.md.',
        '"""',
        "",
        "LOOKUP_CONSUMERS = {",
    ]
    for entity, keys in consumers.items():
        lines.append(f'    "{entity}": (')
        for k in keys:
            lines.append(f'        "{k}",')
        lines.append("    ),")
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = render(build())
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            print("core/lookup_consumers.py is out of date: run  python scripts/build_lookup_consumers.py")
            sys.exit(1)
        print("core/lookup_consumers.py is up to date.")
    else:
        with open(OUT, "w", encoding="utf-8") as fh:
            fh.write(text)
        print(f"wrote {OUT}")
